const assert = require('node:assert/strict');
const { startBackend } = require('./helpers.cjs');
const checks = [];
function check(name, fn) { fn(); checks.push(name); }
const score = { title: 'Giai điệu cộng đồng', bpm: 100, text: '# bpm 100\nQ W E R T' };
(async () => {
  const backend = await startBackend();
  try {
    const alice = backend.client(), bob = backend.client(), carol = backend.client(), guest = backend.client();
    for (const [client, username] of [[alice, 'alice'], [bob, 'bob'], [carol, 'carol']]) assert.equal((await client.raw('register', 'POST', { username, password: 'password123' })).status, 201);
    const original = (await alice.raw('songs', 'PUT', score)).data.song;
    let response = await guest.raw('community');
    check('Private songs never appear in the public feed', () => assert.equal(response.data.posts.length, 0));
    response = await bob.raw('publish', 'POST', { songId: original.id });
    check('Another user cannot publish a private song by guessing its ID', () => assert.equal(response.status, 404));
    response = await alice.raw('publish', 'POST', { songId: original.id, username: 'forged', user_id: bob.uid, description: 'Cùng tập nhé', composer: 'Tác giả gốc', sourceUrl: 'https://example.org/score' });
    assert.equal(response.status, 200); const postId = response.data.id;
    response = await guest.raw('post&id=' + postId);
    check('Public identity comes from the session; public detail exposes only the published snapshot', () => { assert.equal(response.data.post.username, 'alice'); assert.equal(response.data.post.text, score.text); assert.equal(response.data.post.sourceSongId, undefined); });
    response = await bob.raw('post', 'DELETE', { id: postId });
    check('Only the post owner can unpublish', () => assert.equal(response.status, 404));
    await alice.raw('songs', 'PUT', { ...score, text: 'B B B' });
    response = await guest.raw('post&id=' + postId);
    check('Editing a private song does not silently change the public snapshot', () => assert.equal(response.data.post.text, score.text));
    await bob.raw('songs', 'PUT', { ...score, text: 'T T T' });
    response = await bob.raw('copy-post', 'POST', { id: postId });
    assert.equal(response.status, 200); const copyId = response.data.songId;
    check('Copy creates an independent song and renames collisions without overwriting', () => assert.equal(response.data.title, score.title + ' (1)'));
    response = await bob.raw('copy-post', 'POST', { id: postId });
    check('Copying the same post twice is idempotent', () => { assert.equal(response.data.alreadySaved, true); assert.equal(response.data.songId, copyId); });
    response = await bob.raw('songs');
    const copy = response.data.songs.find(song => song.id === copyId);
    check('Private copies retain source credit and original content', () => { assert.equal(copy.text, score.text); assert.equal(copy.source.username, 'alice'); assert.equal(response.data.songs.find(song => song.title === score.title).text, 'T T T'); });
    response = await bob.raw('songs', 'PUT', { ...score, id: copyId, title: 'Bản sao đổi tên' });
    check('Renaming a copied song preserves its ID and source credit', () => { assert.equal(response.status, 200); assert.equal(response.data.song.id, copyId); assert.equal(response.data.song.source.username, 'alice'); });
    response = await bob.raw('songs', 'PUT', { ...score, id: copyId });
    check('Renaming onto another private title fails instead of overwriting', () => { assert.equal(response.status, 409); assert.equal(response.data.error.code, 'TITLE_CONFLICT'); });
    await bob.raw('like', 'PUT', { id: postId, active: true });
    await bob.raw('like', 'PUT', { id: postId, active: true });
    response = await bob.raw('post&id=' + postId);
    check('Likes are idempotent and scoped to each user', () => { assert.equal(response.data.post.likes, 1); assert.equal(response.data.post.liked, true); });
    response = await bob.raw('like', 'PUT', { id: postId, active: false });
    assert.equal(response.data.count, 0);
    await bob.raw('follow', 'PUT', { userId: alice.uid, active: true });
    response = await bob.raw('community&filter=following');
    check('Following feeds include only followed authors', () => { assert.equal(response.data.posts.length, 1); assert.equal(response.data.posts[0].following, true); });
    assert.equal((await carol.raw('community&filter=following')).data.posts.length, 0);
    assert.equal((await guest.raw('community&filter=following')).status, 401);
    response = await alice.raw('follow', 'PUT', { userId: alice.uid, active: true });
    check('Guests cannot mutate social state and users cannot follow themselves', () => assert.equal(response.status, 400));
    assert.equal((await guest.raw('like', 'PUT', { id: postId, active: true })).status, 401);
    response = await bob.raw('comments', 'POST', { postId, content: '<img src=x onerror=alert(1)> Bài hay!' });
    assert.equal(response.status, 200); const commentId = response.data.id;
    response = await guest.raw('comments&postId=' + postId);
    check('Comments are plain text, readable by guests without deletion rights', () => { assert.match(response.data.comments[0].content, /<img/); assert.equal(response.data.comments[0].canDelete, false); });
    response = await carol.raw('comments', 'DELETE', { postId, id: commentId });
    check('Unrelated users cannot delete another comment', () => assert.equal(response.status, 404));
    response = await alice.raw('comments', 'DELETE', { postId, id: commentId });
    check('The post owner can moderate comments on their post', () => assert.equal(response.status, 200));
    assert.equal((await bob.raw('comments', 'POST', { postId, content: 'x'.repeat(1001) })).status, 400);
    response = await alice.raw('publish', 'GET');
    assert.equal(response.status, 400);
    response = await alice.raw('publish&songId=' + original.id);
    check('Owners can retrieve saved publication metadata before updating', () => assert.equal(response.data.publication.description, 'Cùng tập nhé'));
    await alice.raw('publish', 'POST', { songId: original.id, description: 'Bản cập nhật' });
    response = await guest.raw('post&id=' + postId);
    check('Explicit publication updates the snapshot while existing copies stay independent', () => assert.equal(response.data.post.text, 'B B B'));
    assert.equal((await bob.raw('songs')).data.songs.find(song => song.id === copyId).text, score.text);
    const republished = await bob.raw('publish', 'POST', { songId: copyId });
    const secondPostId = republished.data.id;
    response = await guest.raw('post&id=' + secondPostId);
    check('Re-sharing a copied song preserves the original sharing credit', () => { assert.equal(response.data.post.username, 'bob'); assert.equal(response.data.post.creditUsername, 'alice'); });
    await alice.raw('post', 'DELETE', { id: postId });
    assert.equal((await guest.raw('post&id=' + postId)).status, 404);
    assert.equal((await guest.raw('comments&postId=' + postId)).status, 404);
    assert.equal((await carol.raw('copy-post', 'POST', { id: postId })).status, 404);
    response = await bob.raw('songs');
    check('Unpublishing hides the post but preserves already-saved copies and credits', () => { const song = response.data.songs.find(song => song.id === copyId); assert.equal(song.source.username, 'alice'); assert.equal(song.text, score.text); });
    response = await guest.raw('community&q=' + encodeURIComponent('%'));
    check('Search treats wildcard characters as literal text', () => assert.equal(response.data.posts.length, 0));
    // Long MIDI conversions must remain publishable at the same per-layer limit.
    const longScore = (await alice.raw('songs', 'PUT', { title: 'Long MIDI', bpm: 100, text: '# track Melody | piano | oct 0 | vol 90\n' + Array(4096).fill('Q').join(' ') })).data.song;
    response = await alice.raw('publish', 'POST', { songId: longScore.id });
    check('A full 4,096-step MIDI layer remains publishable', () => assert.equal(response.status, 200));
    await alice.raw('post', 'DELETE', { id: response.data.id });
    await alice.raw('songs', 'PUT', { id: longScore.id, title: longScore.title, bpm: 100, text: Array(4097).fill('Q').join(' ') });
    response = await alice.raw('publish', 'POST', { songId: longScore.id });
    check('Publishing rejects layers above the explicit 4,096-step boundary', () => { assert.equal(response.status, 400); assert.equal(response.data.error.code, 'PUBLIC_SCORE_LIMIT'); });
    response = await guest.raw('community&q=bob');
    assert.equal(response.data.posts.length, 1);
    for (let i = 0; i < 22; i++) await backend.database.client.execute({ sql: 'INSERT INTO public_posts (id,user_id,source_song_id,title,bpm,text,published_at,updated_at) VALUES (?,?,?,?,?,?,?,?)', args: [`page-${i}`, alice.uid, `song-page-${i}`, `Page ${i}`, 100, 'Q W E', Date.now() + i, Date.now()] });
    response = await guest.raw('community');
    check('The public feed is paginated and does not include full score bodies', () => { assert.equal(response.data.posts.length, 20); assert.equal(response.data.nextOffset, 20); assert.equal(response.data.posts[0].text, undefined); });
    response = await guest.raw('community&offset=20'); assert.equal(response.data.posts.length, 3);
    await backend.database.client.batch(Array.from({ length: 100 }, (_, i) => ({ sql: 'INSERT INTO songs VALUES (?,?,?,?,?,?)', args: [`full-${i}`, carol.uid, `Full ${i}`, 100, 'Q', Date.now()] })), 'write');
    response = await carol.raw('copy-post', 'POST', { id: secondPostId });
    check('Copy respects the existing library quota', () => assert.equal(response.status, 409));
    response = await bob.raw('songs', 'DELETE', { id: copyId }); assert.equal(response.status, 200);
    assert.equal((await bob.raw('copy-post', 'POST', { id: secondPostId })).status, 200);
    const remainingSource = await backend.database.client.execute({ sql: 'SELECT song_id FROM library_sources WHERE song_id = ?', args: [copyId] });
    check('Deleting a saved copy cleans up its source record', () => assert.equal(remainingSource.rows.length, 0));
  } finally { await backend.close(); }
  const { createDatabase } = require('../server/db.cjs');
  const legacy = createDatabase({ url: 'file::memory:' });
  try {
    await legacy.client.executeMultiple(`
      CREATE TABLE users (id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL, created_at INTEGER NOT NULL);
      CREATE TABLE songs (id TEXT PRIMARY KEY, user_id TEXT NOT NULL, title TEXT NOT NULL, bpm INTEGER NOT NULL, text TEXT NOT NULL, updated_at INTEGER NOT NULL, UNIQUE(user_id,title));
      INSERT INTO users VALUES ('legacy','legacy_user','test-hash',1);
      INSERT INTO songs VALUES ('old-song','legacy','Bài cũ',100,'Q W E',1);
    `);
    await legacy.ready();
    const songs = await legacy.client.execute('SELECT title FROM songs');
    const added = await legacy.client.execute("SELECT name FROM sqlite_master WHERE type='table' AND name IN ('public_posts','library_sources','post_likes','follows','post_comments')");
    check('Existing databases gain community tables without losing legacy users or songs', () => { assert.equal(songs.rows[0].title, 'Bài cũ'); assert.equal(added.rows.length, 5); });
  } finally { legacy.close(); }
  console.log(checks.map((name, i) => `${i + 1}. PASS ${name}`).join('\n'));
  console.log(`\n${checks.length} community checks passed against SQLite.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
