const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { startBackend } = require('./helpers.cjs');
const { createDatabase } = require('../server/db.cjs');
const output = [];
function check(name, fn) { fn(); output.push(name); }
const sample = { title: 'Bài / thử 🎵', bpm: 100, text: '# bpm 100\nQ W E' };
(async () => {
  let time = Date.now();
  const backend = await startBackend({ now: () => time });
  try {
    const alice = backend.client(), bob = backend.client(), guest = backend.client();
    let response = await guest.raw('songs');
    check('Unauthenticated requests cannot read songs', () => assert.equal(response.status, 401));
    response = await alice.raw('register', 'POST', { username: '  ALICE_01  ', password: 'password123' });
    check('Register creates a normalized username and HttpOnly session, without email', () => {
      assert.equal(response.status, 201); assert.equal(response.data.user.username, 'alice_01');
      assert.match(response.headers.get('set-cookie'), /HttpOnly; SameSite=Lax/);
      assert.equal(response.headers.get('cache-control'), 'private, no-store');
      assert.ok(!JSON.stringify(response.data).includes('password'));
    });
    const users = await backend.database.client.execute('SELECT * FROM users');
    const sessions = await backend.database.client.execute('SELECT * FROM sessions');
    check('Database stores a salted password hash and token hash, not raw credentials', () => {
      assert.match(users.rows[0].password_hash, /^scrypt\$/); assert.ok(!users.rows[0].password_hash.includes('password123'));
      assert.notEqual(sessions.rows[0].token_hash, alice.cookie.split('=')[1]);
    });
    response = await bob.raw('register', 'POST', { username: 'alice_01', password: 'password123' });
    check('Duplicate usernames return 409', () => assert.equal(response.status, 409));
    response = await bob.raw('register', 'POST', { username: 'bob', password: 'password123' });
    assert.equal(response.status, 201);
    response = await alice.raw('songs', 'PUT', { ...sample, user_id: bob.uid });
    const aliceSong = response.data.song;
    check('Save ignores a forged owner and derives ownership from the cookie', () => assert.equal(response.status, 200));
    response = await bob.raw('songs');
    check('Another account has no access to the first account library', () => assert.equal(response.data.songs.length, 0));
    response = await bob.raw('songs', 'DELETE', { id: aliceSong.id });
    check('Knowing another song ID does not allow deletion', () => assert.equal(response.status, 404));
    response = await bob.raw('songs', 'PUT', { ...sample, id: aliceSong.id, text: 'T T T' });
    assert.equal(response.status, 404);
    response = await alice.raw('songs');
    check('A forged ID cannot overwrite another account song', () => assert.equal(response.data.songs[0].text, sample.text));
    response = await alice.raw('songs', 'PUT', { ...sample, bpm: 120 });
    check('Saving the same title updates one song and preserves its ID', () => { assert.equal(response.data.song.id, aliceSong.id); assert.equal(response.data.song.bpm, 120); });
    response = await alice.raw('import', 'POST', { songs: [sample, { ...sample, title: 'Bài thứ hai' }] });
    check('Import adds new titles and preserves existing songs', () => { assert.equal(response.data.imported, 1); assert.equal(response.data.skipped, 1); });
    response = await alice.raw('songs', 'PUT', { ...sample, bpm: 0 });
    assert.equal(response.status, 400);
    response = await alice.raw('songs', 'PUT', { ...sample, text: 'Q'.repeat(200001) });
    check('Server rejects invalid BPM and oversized song content', () => assert.equal(response.status, 400));
    response = await alice.raw('songs', 'DELETE', { id: aliceSong.id }, { Origin: 'https://attacker.invalid' });
    assert.equal(response.status, 403);
    response = await alice.raw('logout', 'POST', {}, { 'Content-Type': 'text/plain' });
    check('Cross-site writes and non-JSON mutations are rejected', () => assert.equal(response.status, 415));
    response = await alice.raw('songs', 'PUT', sample, { 'X-Sky-User': bob.uid });
    check('A stale tab cannot write into a newly signed-in account', () => { assert.equal(response.status, 409); assert.equal(response.data.error.code, 'SESSION_CHANGED'); });
    const oldCookie = alice.cookie;
    response = await alice.raw('logout', 'POST', {});
    assert.equal(response.status, 200); assert.match(response.headers.get('set-cookie'), /Max-Age=0/);
    alice.cookie = oldCookie;
    response = await alice.raw('session');
    check('Logout revokes the server session, including replay of the old cookie', () => assert.equal(response.data.user, null));
    response = await alice.raw('login', 'POST', { username: 'alice_01', password: 'wrong' });
    assert.equal(response.status, 401);
    response = await alice.raw('login', 'POST', { username: 'missing', password: 'wrong' });
    check('Missing users and wrong passwords return the same credential error', () => { assert.equal(response.status, 401); assert.equal(response.data.error.code, 'INVALID_CREDENTIALS'); });
    response = await alice.raw('login', 'POST', { username: 'ALICE_01', password: 'password123' });
    assert.equal(response.status, 200);
    response = await alice.raw('songs');
    check('Logging back in restores saved songs', () => assert.equal(response.data.songs.length, 2));
    time += 8 * 24 * 60 * 60 * 1000;
    response = await alice.raw('songs');
    check('Expired sessions lose access', () => assert.equal(response.status, 401));
    const limited = backend.client();
    // Điền sẵn cửa sổ giới hạn để kiểm tra chặn mà không chạy 16 lần scrypt.
    const { createHash } = require('node:crypto');
    const key = createHash('sha256').update('login-user:limited').digest('hex');
    await backend.database.client.execute({ sql: 'INSERT INTO auth_limits VALUES (?, ?, ?)', args: [key, 15, time + 900000] });
    response = await limited.raw('login', 'POST', { username: 'limited', password: 'password123' });
    check('Persistent login throttling blocks repeated attempts', () => assert.equal(response.status, 429));
    response = await guest.raw('register', 'GET');
    assert.equal(response.status, 405);
    response = await guest.raw('unknown');
    check('Unknown actions and unsupported methods are rejected', () => assert.equal(response.status, 404));
    const injection = backend.client();
    response = await injection.raw('login', 'POST', { username: "' OR 1=1 --", password: 'password123' });
    check('Invalid identities are rejected before SQL authentication', () => assert.equal(response.status, 400));
    const concurrent = await Promise.all([backend.client(), backend.client()].map(account => account.raw('register', 'POST', { username: 'concurrent_user', password: 'password123' })));
    check('Concurrent registration of one username creates exactly one account', () => assert.deepEqual(concurrent.map(value => value.status).sort(), [201, 409]));
    const quota = backend.client();
    response = await quota.raw('register', 'POST', { username: 'quota_user', password: 'password123' });
    assert.equal(response.status, 201);
    await backend.database.client.batch(Array.from({ length: 100 }, (_, i) => ({ sql: 'INSERT INTO songs VALUES (?, ?, ?, ?, ?, ?)', args: [`quota-${i}`, quota.uid, `Quota ${i}`, 100, 'Q W E', time] })), 'write');
    response = await quota.raw('songs', 'PUT', { ...sample, title: 'Quota 0', bpm: 110 });
    assert.equal(response.status, 200);
    response = await quota.raw('songs', 'PUT', sample);
    check('Full libraries can update existing titles but cannot add beyond 100 songs', () => { assert.equal(response.status, 409); assert.equal(response.data.error.code, 'LIBRARY_FULL'); });
    const { createHandler } = require('../server/handler.cjs');
    const secureHandler = createHandler({ getDatabase: () => backend.database, secureCookies: true, now: () => time });
    const captured = { headers: {}, setHeader(name, value) { this.headers[name] = value; }, end(value) { this.body = JSON.parse(value); } };
    await secureHandler({ url: '/api/account?action=register', method: 'POST', headers: { host: 'sky.vercel.app', origin: 'https://sky.vercel.app', 'content-type': 'application/json' }, body: { username: 'vercel_user', password: 'password123' } }, captured);
    check('Production accepts Vercel-parsed bodies and sets a Secure __Host cookie', () => {
      assert.equal(captured.statusCode, 201); assert.match(captured.headers['Set-Cookie'], /^__Host-sky_session=/); assert.match(captured.headers['Set-Cookie'], /; Secure$/);
    });
    const missingConfig = createHandler({ getDatabase() { throw Object.assign(new Error('private setup detail'), { code: 'SETUP_REQUIRED' }); } });
    await missingConfig({ url: '/api/account?action=session', method: 'GET', headers: {} }, captured);
    check('Missing production database configuration fails closed with a safe setup message', () => {
      assert.equal(captured.statusCode, 503); assert.equal(captured.body.error.code, 'SETUP_REQUIRED'); assert.ok(!JSON.stringify(captured.body).includes('private setup detail'));
    });
  } finally { await backend.close(); }
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'sky-sqlite-'));
  const url = pathToFileURL(path.join(temp, 'persist.db')).href;
  const first = createDatabase({ url });
  await first.ready();
  await first.client.execute({ sql: 'INSERT INTO users VALUES (?, ?, ?, ?)', args: ['persist', 'persistent_user', 'test-hash', Date.now()] }); first.close();
  const second = createDatabase({ url });
  await second.ready();
  const persisted = await second.client.execute('SELECT username FROM users'); second.close();
  check('SQLite data and idempotent schema survive closing and reopening the database', () => assert.equal(persisted.rows[0].username, 'persistent_user'));
  console.log(output.map((name, i) => `${i + 1}. PASS ${name}`).join('\n'));
  console.log(`\n${output.length} backend checks passed against real SQLite.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
